#!/bin/bash
# Release determinism control (P1). N release builds per group, all inside Gradle:
#   A  plugin NOT applied, no compile daemons of this project, app not running
#      (a throwaway Gradle project whose Exec task runs the plugin's release commands.sh)
#   B  plugin applied, hot-reload session live (daemons up, app running, a reload + revert before each build);
#      the compiler JVM's environment and system properties are dumped during the build
#   C  plugin applied, session over: daemons stopped, app terminated
# Records the __text sha256 of each build and the set of hashes per group.
# Usage: UDID=<udid> HR_UDID=<udid> N=5 ./accept-release-control.sh > accept-plugin-p1-release-control.txt
set -u
cd "$(dirname "$0")"
N=${N:-5}
UDID=${UDID:-booted}
R=build/hotreload/release
OUT=build/hotreload/release-control
JCMD="$JAVA_HOME/bin/jcmd"
H_DIR=$(cd ~ && pwd)   # home directory, replaced by a placeholder in the evidence files
clean() { sed -e "s#${H_DIR}#<HOME>#g"; }
text_sha() { segedit "$1" -extract __TEXT __text "$1.text" && shasum -a 256 "$1.text" | cut -c1-12; }
rm -rf "$OUT" && mkdir -p "$OUT"

# The release commands, generated by the plugin (same commands in every group).
./gradlew -q hotReloadVerifyRelease -Pcmp.hotreload.releaseBaseline=true --console=plain > /dev/null 2>&1
cp "$R/baseline/commands.sh" "$OUT/commands.template.sh"
cp "$R/baseline/fingerprint.txt" "$OUT/fingerprint.reference.txt"
echo "release commands: $(grep -c kotlinc-native "$OUT/commands.template.sh") compiler invocations; module-name and TMPDIR fixed"

# ---------------------------------------------------------------- A
echo "== A: plugin not applied, no daemons, app not running"
./gradlew -q hotReloadDaemonStop --console=plain 2>&1 | clean
xcrun simctl terminate "$UDID" com.example.composehr 2>/dev/null
P=$(pwd)/build/release-control-gradle
rm -rf "$P" && mkdir -p "$P"
cat > "$P/settings.gradle.kts" <<'EOF'
rootProject.name = "release-control"
EOF
cat > "$P/build.gradle.kts" <<'EOF'
// No hot-reload plugin here: an ordinary Exec task runs the release compiler invocations.
tasks.register<Exec>("releaseBuild") {
    commandLine("bash", providers.gradleProperty("script").get())
    outputs.upToDateWhen { false }
}
EOF
echo "daemons of this project: $(pgrep -f "HrCompileDaemon.*$(pwd)" | wc -l | tr -d ' '); app running: $(pgrep -f "Devices/$UDID/.*ComposeHR.app" | wc -l | tr -d ' ')"
for i in $(seq 1 "$N"); do
  d="$(pwd)/$OUT/A$i"; mkdir -p "$d/klib"
  sed -e "s#$(pwd)/$R/baseline/#$d/#g" "$OUT/commands.template.sh" > "$d/commands.sh"
  ./gradlew -q -p "$P" releaseBuild -Pscript="$d/commands.sh" --console=plain > "$d/build.out" 2>&1 || { echo "A$i build failed"; tail -5 "$d/build.out"; }
  echo "A$i text=$(text_sha "$d/ComposeHR-release.kexe")"
done

# ---------------------------------------------------------------- B
echo "== B: plugin applied, session live"
./gradlew -q hotReloadPackage --console=plain > "$OUT/B-package.out" 2>&1
./gradlew hotReloadRun --console=plain 2>&1 | grep -E 'app started' | clean
tr '\r' '\n' < launch.log | grep -m1 'EH OK'
reqs() { cat build/hotreload/daemon-*.log 2>/dev/null | grep -c '^REQ'; }
newest() { find build/hotreload/ic build/hotreload/auto-cache -type f -newer "$1" 2>/dev/null | wc -l | tr -d ' '; }
for i in $(seq 1 "$N"); do
  sed -i '' "s/UI_MARK = \"[^\"]*\"/UI_MARK = \"ctl-b$i\"/" ui/src/main/kotlin/ui.kt
  ./gradlew -q hotReload --console=plain > /dev/null 2>&1
  for t in $(seq 1 50); do tr '\r' '\n' < launch.log | grep -q "RENDER_UI ctl-b$i" && break; sleep 0.2; done
  echo "B$i reload ctl-b$i: $(tr '\r' '\n' < launch.log | grep -c "RENDER_UI ctl-b$i") renders"
  git checkout -q -- ui/src
  ./gradlew -q hotReload --console=plain > /dev/null 2>&1
  pid=$(pgrep -f "Devices/$UDID/.*ComposeHR.app/ComposeHR")
  d="$OUT/B$i"; mkdir -p "$d"; touch "$d/.start"; r0=$(reqs)
  # Dump every compiler JVM started by this release build (not the HrCompileDaemon processes).
  ( seen=" "; while [ ! -f "$d/.done" ]; do
      for p in $(pgrep -f 'konan.home' ); do
        case "$seen" in *" $p "*) continue ;; esac
        cmd=$(ps -ww -o command= -p "$p" 2>/dev/null) || continue
        case "$cmd" in *HrCompileDaemon*|"") continue ;; esac
        seen="$seen$p "
        { echo "### pid $p"; echo "$cmd"; echo "--- env (names only; values are never recorded)"; ps -wwE -o command= -p "$p" | tr ' ' '\n' | grep -oE '^[A-Z_][A-Z0-9_]*=' ; \
          echo "--- system properties"; "$JCMD" "$p" VM.system_properties 2>&1; } >> "$d/compiler-jvm.txt"
      done; sleep 0.5; done ) &
  POLL=$!
  ./gradlew -q hotReloadVerifyRelease -Pcmp.hotreload.releaseBaseline=true --console=plain > "$d/build.out" 2>&1 || { echo "B$i build failed"; tail -5 "$d/build.out"; }
  touch "$d/.done"; wait $POLL
  cp "$R/baseline/fingerprint.txt" "$d/" ; cp "$R/baseline/commands.sh" "$d/"
  jvms=$(grep -c '^### pid' "$d/compiler-jvm.txt" 2>/dev/null)
  leak=$(grep -E 'KALDO_|KONAN_HOT_RELOAD|hr-compile|hr-klib|HRC_|/hotreload/ic|ic-cache-dir|auto-cache|compilation-scheme|incremental-compilation' "$d/compiler-jvm.txt" "$d/commands.sh" | wc -l | tr -d ' ')
  echo "B$i text=$(grep text.sha256 "$d/fingerprint.txt" | cut -c13-24) app_pid=$pid alive=$(pgrep -f "Devices/$UDID/.*ComposeHR.app/ComposeHR" | wc -l | tr -d ' ') compiler_jvms_dumped=$jvms leak_lines=$leak daemon_requests_during_build=$(( $(reqs) - r0 )) ic_autocache_files_written=$(newest "$d/.start")"
done

# ---------------------------------------------------------------- C
echo "== C: session over (daemons stopped, app terminated), plugin applied"
./gradlew -q hotReloadDaemonStop --console=plain 2>&1 | clean
xcrun simctl terminate "$UDID" com.example.composehr 2>/dev/null
echo "daemons of this project: $(pgrep -f "HrCompileDaemon.*$(pwd)" | wc -l | tr -d ' ')"
for i in $(seq 1 "$N"); do
  d="$OUT/C$i"; mkdir -p "$d"
  ./gradlew -q hotReloadVerifyRelease -Pcmp.hotreload.releaseBaseline=true --console=plain > "$d/build.out" 2>&1 || { echo "C$i build failed"; tail -5 "$d/build.out"; }
  cp "$R/baseline/fingerprint.txt" "$d/"
  echo "C$i text=$(grep text.sha256 "$d/fingerprint.txt" | cut -c13-24)"
done

echo "== summary (distinct __text hashes per group)"
for g in A B C; do
  printf '%s: ' "$g"
  for i in $(seq 1 "$N"); do
    f="$OUT/$g$i/fingerprint.txt"; [ "$g" = A ] && f="$OUT/A$i/ComposeHR-release.kexe.text"
    if [ "$g" = A ]; then shasum -a 256 "$f" | cut -c1-12; else grep text.sha256 "$f" | cut -c13-24; fi
  done | sort | uniq -c | awk '{printf "%s x%s  ", $2, $1}'; echo
done
